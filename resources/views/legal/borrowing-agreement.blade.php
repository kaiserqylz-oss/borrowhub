                            4. Rental Duration and Total Amount
                        </h3>
                        <p class="mt-2">
                            BorrowHub calculates the estimated rental amount
                            by multiplying the item's daily price by the
                            selected number of calendar days. The start date
                            and end date are both included in the calculation.
                        </p>
                        <p class="mt-2">
                            For example, an item priced at ₱100 per day for
                            three calendar days has an estimated rental total
