                            <li>Provide accurate account and request information.</li>
                            <li>Use the borrowed item carefully and for its intended, lawful purpose.</li>
                            <li>Follow the owner's reasonable operating and safety instructions.</li>
                            <li>Do not lend, transfer, sell, or sub-rent the item to another person without the owner's permission.</li>
                            <li>Return the item on the agreed date and coordinate the return with the owner.</li>
                            <li>Notify the owner promptly about delays, damage, loss, or other problems.</li>
