                        <h3 class="text-lg font-bold text-gray-900">
                            5. Payment and Deposits
                        </h3>
                        <p class="mt-2">
                            Before handover, both parties should confirm the
                            payment method, payment deadline, whether a
                            deposit is required, and the conditions for
                            returning any deposit. Both parties should keep
                            receipts or other proof of payment.
                        </p>
                        <p class="mt-2">
                            BorrowHub does not automatically collect,
                            transfer, hold, or refund payments unless an
                            explicitly supported payment feature is provided.
                            Users should not treat a request or approval
                            status as proof that payment has been made.
                        </p>
                    </section>

