                        <h3 class="text-lg font-bold text-gray-900">
                            3. Item Owner's Responsibilities
                        </h3>
                        <ul class="mt-2 list-disc pl-6 space-y-2">
                            <li>Have the right and authority to lend the listed item.</li>
                            <li>Describe the item and its condition honestly, including known defects that affect safe use.</li>
                            <li>Make reasonable arrangements for the agreed handover.</li>
                            <li>Disclose the rental price and discuss any deposit or additional charges before the transaction.</li>
                            <li>Inspect the item with the borrower at handover and return where reasonably possible.</li>
                            <li>Confirm receipt of a returned item and communicate any concerns promptly.</li>
                        </ul>
                    </section>

