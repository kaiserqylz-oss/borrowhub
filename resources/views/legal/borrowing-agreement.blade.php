                        </h3>
                        <p class="mt-2">
                            The borrower must notify the owner if the item
                            cannot be returned on time and request an
                            extension. An extension is effective only when
                            the owner agrees. Any additional rental amount
                            or late fee must be clearly agreed upon before
                            it is charged and must comply with applicable law.
                        </p>
