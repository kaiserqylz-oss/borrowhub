                            8. Damage, Loss, and Compensation
                        </h3>
                        <p class="mt-2">
                            The borrower should return the item in the
                            condition received, allowing for ordinary wear
                            from proper use. Damage, loss, or a dispute
                            should be reported promptly. Both parties should
                            preserve before-and-after photos, messages,
                            receipts, and other relevant evidence.
                        </p>
                        <p class="mt-2">
                            Compensation must be based on the facts, the
                            parties' agreed terms, and applicable law.
                            Neither a complaint nor a report alone establishes
                            fault or a specific amount owed.
