                            The parties should first attempt to resolve
                            disagreements respectfully and directly using
                            their retained records. Either party may use
                            BorrowHub's reporting function if available.
                            An administrator may review a report under the
                            platform's procedures, but the platform does not
                            guarantee a particular decision or recovery of
