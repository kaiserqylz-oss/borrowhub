                            6. Cancellation Process
                        </h3>
                        <ol class="mt-2 list-decimal pl-6 space-y-2">
                            <li>Contact the other party as soon as possible and explain the reason for cancellation.</li>
                            <li>Before the item is handed over, both parties should confirm the cancellation and any revised arrangement in writing through a retained message or other record.</li>
                            <li>If payment or a deposit was already made, follow the cancellation and refund terms agreed upon before payment, subject to applicable law.</li>
                            <li>Keep any relevant messages, receipts, and confirmation as evidence if a disagreement arises.</li>
                        </ol>
                        <p class="mt-2">
                            Do not assume that cancellation automatically
                            changes a request or transaction's status in
                            BorrowHub. Use the available application
                            functions and contact the other party to clarify
                            the arrangement.
